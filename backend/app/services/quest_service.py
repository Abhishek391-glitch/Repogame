import os
import logging
from typing import List, Dict, Any, Optional
from app.models.schemas import Quest, QuestStep, KnowledgeCheck
from app.services.tree_analyzer import classify_node, is_entry_point

logger = logging.getLogger(__name__)

class QuestService:
    def generate_quests_for_repo(
        self,
        owner: str,
        repo: str,
        entry_points: List[str],
        config_files: List[str],
        test_files: List[str],
        doc_files: List[str],
        all_paths: List[str],
        has_readme: bool
    ) -> List[Quest]:
        """
        Dynamically generate 5 grounded learning quests based on actual detected repository files.
        If a file category is absent, generates a relevant investigation quest.
        """
        quests: List[Quest] = []

        # -------------------------------------------------------------
        # QUEST 1: Find the Project's Entry Point (100 XP)
        # -------------------------------------------------------------
        best_entry = entry_points[0] if entry_points else None
        if not best_entry:
            # Fallback to plausible file or readme
            best_entry = "README.md" if has_readme else (all_paths[0] if all_paths else "root")

        entry_options = [best_entry]
        # Pick 3 plausible distractors from all_paths
        distractors = [p for p in all_paths if p != best_entry and not is_entry_point(p)][:3]
        while len(distractors) < 3:
            distractors.append(f"distractor_{len(distractors)}.tmp")
        all_entry_choices = [distractors[0], best_entry, distractors[1], distractors[2]]
        correct_entry_idx = 1

        quests.append(Quest(
            id="quest-entry",
            title="Find the Project's Entry Point",
            category="entrypoint",
            difficulty="Beginner",
            xp_reward=100,
            estimated_minutes=5,
            objective="Discover where program execution or module bootstrapping begins.",
            why_it_matters="Understanding the entry point gives you the 'front door' of the application, showing how CLI arguments or HTTP servers spin up.",
            steps=[
                QuestStep(
                    step_number=1,
                    instruction=f"Examine project documentation and root files in the tree.",
                    hint="Look for standard runner names like main, app, index, or cli.",
                    target_path="README.md" if has_readme else None
                ),
                QuestStep(
                    step_number=2,
                    instruction=f"Locate the candidate entry file `{best_entry}`.",
                    hint=f"Check the file path `{best_entry}` in the File Explorer or Repository Map.",
                    target_path=best_entry
                ),
                QuestStep(
                    step_number=3,
                    instruction="Answer the verification question below to claim your XP reward.",
                    hint="Reflect on which file initiates the primary workflow."
                )
            ],
            relevant_paths=[best_entry] + ([p for p in entry_points if p != best_entry][:2]),
            knowledge_check=KnowledgeCheck(
                question=f"Based on the repository layout, which of the following files serves as a primary entry point or launchpad?",
                options=all_entry_choices,
                correct_index=correct_entry_idx,
                explanation=f"`{best_entry}` is recognized as a primary execution entry point based on repository structure conventions."
            ),
            hints=[
                "Most applications start from a file named main, app, or index.",
                "Package manifests (e.g., package.json 'main' or pyproject.toml 'scripts') declare entry points."
            ]
        ))

        # -------------------------------------------------------------
        # QUEST 2: Decode the Configuration (150 XP)
        # -------------------------------------------------------------
        primary_config = config_files[0] if config_files else ("pyproject.toml" if "python" in str(all_paths).lower() else "package.json")
        has_real_config = bool(config_files)

        config_options = [
            "It stores user passwords and private database keys.",
            f"It declares project dependencies, metadata, and build/run scripts ({primary_config}).",
            "It contains binary assets and image previews.",
            "It is automatically generated by the operating system and should be deleted."
        ]

        quests.append(Quest(
            id="quest-config",
            title="Decode the Configuration",
            category="config",
            difficulty="Beginner",
            xp_reward=150,
            estimated_minutes=7,
            objective=f"Understand how dependencies and project settings are configured via `{primary_config}`.",
            why_it_matters="Manifests reveal external libraries, version constraints, and required runtime environments before you write code.",
            steps=[
                QuestStep(
                    step_number=1,
                    instruction=f"Find the manifest `{primary_config}` in the File Explorer.",
                    hint="Configuration files are usually located in the repository root directory.",
                    target_path=primary_config if has_real_config else None
                ),
                QuestStep(
                    step_number=2,
                    instruction="Inspect its declared dependencies or build tools.",
                    hint="Notice which third-party packages the repository relies upon.",
                    target_path=primary_config if has_real_config else None
                ),
                QuestStep(
                    step_number=3,
                    instruction="Confirm the primary purpose of this manifest in the knowledge check.",
                    hint="Manifests define what needs to be installed to build or run the project."
                )
            ],
            relevant_paths=config_files[:3] if config_files else [primary_config],
            knowledge_check=KnowledgeCheck(
                question=f"What is the primary role of `{primary_config}` in this repository?",
                options=config_options,
                correct_index=1,
                explanation=f"`{primary_config}` serves as the authoritative manifest specifying libraries, compiler/interpreter targets, and build parameters."
            ),
            hints=[
                "Manifests prevent dependency hell by recording exact library versions.",
                "Package managers read this file when running 'install' commands."
            ]
        ))

        # -------------------------------------------------------------
        # QUEST 3: Explore the Test Suite (200 XP)
        # -------------------------------------------------------------
        test_sample = test_files[0] if test_files else None
        test_q_options = [
            "Tests ensure critical functionality doesn't break when new changes are introduced.",
            "Tests are only used to slow down the CI/CD pipeline.",
            "Tests contain production secrets for testing servers.",
            "Tests replace the need for writing documentation."
        ]

        quests.append(Quest(
            id="quest-test",
            title="Explore the Test Suite",
            category="test",
            difficulty="Beginner to Intermediate",
            xp_reward=200,
            estimated_minutes=8,
            objective="Understand how automated tests verify behavior in this codebase.",
            why_it_matters="Reading tests is one of the fastest ways to learn how functions are intended to be called with realistic inputs.",
            steps=[
                QuestStep(
                    step_number=1,
                    instruction="Search for test directories (e.g. `tests/`, `__tests__/`, or files matching `*test*`).",
                    hint="Check the Test category in the Repository Map filter.",
                    target_path=test_sample
                ),
                QuestStep(
                    step_number=2,
                    instruction=f"Inspect `{test_sample or 'test files'}` to observe how assertions are written.",
                    hint="Look for assertions or test cases that verify expected outputs.",
                    target_path=test_sample
                ),
                QuestStep(
                    step_number=3,
                    instruction="Complete the verification check regarding automated testing.",
                    hint="Think about why open-source maintainers require tests on pull requests."
                )
            ],
            relevant_paths=test_files[:3] if test_files else [],
            knowledge_check=KnowledgeCheck(
                question="Why is inspecting the test suite especially valuable for first-time contributors?",
                options=test_q_options,
                correct_index=0,
                explanation="Tests provide concrete, executable examples of how modules work and protect contributors from unintentional regressions."
            ),
            hints=[
                "Tests act as executable specifications for code behavior.",
                "Most repositories require all existing and new tests to pass before merging PRs."
            ]
        ))

        # -------------------------------------------------------------
        # QUEST 4: Trace a Core Component (250 XP)
        # -------------------------------------------------------------
        source_candidates = [p for p in all_paths if p.endswith((".py", ".ts", ".js", ".go", ".rs", ".java")) and not is_entry_point(p) and p not in test_files]
        core_sample = source_candidates[0] if source_candidates else (all_paths[0] if all_paths else "core")

        quests.append(Quest(
            id="quest-feature",
            title="Trace a Core Component",
            category="feature",
            difficulty="Intermediate",
            xp_reward=250,
            estimated_minutes=10,
            objective="Follow how data and logic flow through internal modules.",
            why_it_matters="Open-source contributors need to know how helper modules connect to core logic to add new features safely.",
            steps=[
                QuestStep(
                    step_number=1,
                    instruction=f"Examine `{core_sample}` in the Repository Map or File Explorer.",
                    hint="Look at which other internal modules or external libraries this file imports.",
                    target_path=core_sample
                ),
                QuestStep(
                    step_number=2,
                    instruction="Use the 'Explain with AI' tool to get a summary of its key components.",
                    hint="The AI will break down classes, functions, and relationships.",
                    target_path=core_sample
                ),
                QuestStep(
                    step_number=3,
                    instruction="Answer the architectural understanding question below.",
                    hint="Consider the principle of separation of concerns in modular codebases."
                )
            ],
            relevant_paths=[core_sample] + source_candidates[1:3],
            knowledge_check=KnowledgeCheck(
                question="When adding a new feature to an established repository, what is the best practice?",
                options=[
                    "Rewrite all existing files from scratch.",
                    "Identify existing related modules, follow existing conventions, and add targeted tests.",
                    "Submit a pull request without checking if the codebase compiles.",
                    "Directly commit changes to the main branch without a branch or PR."
                ],
                correct_index=1,
                explanation="Respecting existing architecture and conventions ensures clean reviews and maintainer trust."
            ),
            hints=[
                "Look for existing design patterns before introducing new abstractions.",
                "Good contributions blend seamlessly into the existing repository style."
            ]
        ))

        # -------------------------------------------------------------
        # QUEST 5: Prepare for a First Contribution (200 XP)
        # -------------------------------------------------------------
        contrib_file = next((p for p in doc_files if "contributing" in p.lower()), None)
        doc_sample = contrib_file or ("README.md" if has_readme else "CONTRIBUTING.md")

        quests.append(Quest(
            id="quest-contrib",
            title="Prepare for a First Contribution",
            category="contributing",
            difficulty="Beginner",
            xp_reward=200,
            estimated_minutes=7,
            objective="Understand the project's contribution guidelines, PR checklist, and newcomer expectations.",
            why_it_matters="Every project has specific requirements for formatting, branching, commit messages, and testing.",
            steps=[
                QuestStep(
                    step_number=1,
                    instruction=f"Locate contribution guidelines (`{doc_sample}`).",
                    hint="Check root docs or `.github/` folder for CONTRIBUTING.md or guidelines.",
                    target_path=doc_sample
                ),
                QuestStep(
                    step_number=2,
                    instruction="Review the Contributor Readiness Dashboard in RepoQuest.",
                    hint="The dashboard scans for license, issue templates, test suites, and setup instructions."
                ),
                QuestStep(
                    step_number=3,
                    instruction="Pass the contributor readiness question to claim your final quest badge.",
                    hint="Remember the golden rules of open-source etiquette."
                )
            ],
            relevant_paths=[p for p in doc_files if any(k in p.lower() for k in ("contributing", "readme", "code_of_conduct", "license"))],
            knowledge_check=KnowledgeCheck(
                question="Before opening a new pull request on a public repository, what should you always do?",
                options=[
                    "Ping all maintainers on personal social media immediately.",
                    "Check existing issues/PRs, read CONTRIBUTING.md, and ensure local tests pass.",
                    "Delete all documentation to keep the codebase compact.",
                    "Submit unfinished code and ask maintainers to write your tests."
                ],
                correct_index=1,
                explanation="Reading guidelines and verifying test suites demonstrates respect for maintainers' volunteer time."
            ),
            hints=[
                "Most repositories welcome questions in Discussions or on labeled 'good first issue' tickets.",
                "Clean git branches and descriptive PR descriptions speed up reviews."
            ]
        ))

        return quests

quest_service = QuestService()
